// ArkTS emitter. Structure mirrors Dashiell json-gen: a tiny writer owns
// indentation, the emitter owns the class/interface tree, output is deterministic.

import { createHash } from 'node:crypto';

export function render(catalog, sites, catalogText, appName = 'Dashiell') {
  const events = catalog.events;
  const eventsSha = sha256(catalogText);
  const sitesCanonical = events.map((event) => {
    const site = sites[event.name];
    return [
      event.name, site.file, site.line, site.column, site.className, site.methodName,
    ].join('\u0001');
  }).join('\u0002');
  const sitesSha = sha256(sitesCanonical);

  const w = new Writer();
  w.line(`// GENERATED by ${appName} log-gen v1. DO NOT EDIT.`);
  w.line(`// Events SHA-256: ${eventsSha}`);
  w.line(`// Sites SHA-256: ${sitesSha}`);
  w.line('// Regenerate: node tools/log-gen/cli.mjs --write');
  w.line('');
  w.line("import { Logger } from './Logger';");
  w.line("import { F, L, LogLevel, LogSite } from './LogCore';");

  for (const event of events) {
    if (event.fields.length === 0) {
      continue;
    }
    w.line('');
    writeEventDoc(w, event);
    w.block(`export interface ${fieldsType(event)}`, () => {
      for (const field of event.fields) {
        w.line(`${field.name}${field.required ? '' : '?'}: ${fieldType(field)};`);
      }
    });
  }

  w.line('');
  w.line('/**');
  w.line(' * 构建期生成的日志事件 / generated log events.');
  w.line(' * 每个事件对应唯一调用点,文件/行/列/类/方法由 log-gen 扫描写入。');
  w.line(' */');
  w.block('export class LogEvents', () => {
    for (let i = 0; i < events.length; i++) {
      const event = events[i];
      const site = sites[event.name];
      if (i > 0) {
        w.line('');
      }
      w.line(`private static readonly SITE_${constName(event.name)}: LogSite = new LogSite(`);
      w.depth++;
      w.line(`${str(site.file)},`);
      w.line(`${site.line},`);
      w.line(`${site.column},`);
      w.line(`${str(site.className)},`);
      w.line(`${str(site.methodName)},`);
      w.line(`${str(event.name)},`);
      w.depth--;
      w.line(');');
      w.line('');
      writeEventDoc(w, event);
      w.block(`static ${event.name}(${signature(event)}): void`, () => {
        w.line(`Logger.logAt(LogLevel.${event.level}, ${str(event.tag)}, LogEvents.SITE_${constName(event.name)},`);
        if (event.fields.length === 0) {
          const tail = event.error ? ', [], error);' : ', []);';
          w.line(`  L(${str(event.zh)}, ${str(event.en)})${tail}`);
          return;
        }
        w.line(`  L(${str(event.zh)}, ${str(event.en)}), [`);
        w.depth++;
        for (const field of event.fields) {
          w.line(`F(${str(field.name)}, fields.${field.name}),`);
        }
        w.depth--;
        w.line(`]${event.error ? ', error);' : ');'}`);
      });
    }
  });
  return w.toString();
}

export function fieldsType(event) {
  return `${event.name[0].toUpperCase()}${event.name.slice(1)}Fields`;
}

export function constName(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
}

function signature(event) {
  const parts = [];
  if (event.fields.length > 0) {
    parts.push(`fields: ${fieldsType(event)}`);
  }
  if (event.error) {
    parts.push('error?: Object');
  }
  return parts.join(', ');
}

function fieldType(field) {
  switch (field.type) {
    case 'string':
      return 'string';
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'json':
      return 'Object';
    default:
      throw new Error(`unsupported field type: ${field.type}`);
  }
}

function writeEventDoc(w, event) {
  w.line('/**');
  w.line(` * ${docText(event.zh)} / ${docText(event.en)}`);
  if (event.fields.length > 0) {
    const names = event.fields.map((field) => {
      const zh = field.zh === '' ? '' : ` ${docText(field.zh)}`;
      const en = field.en === '' ? '' : ` ${docText(field.en)}`;
      return `${field.name}${zh}${en}`;
    });
    w.line(` * fields: ${names.join('; ')}`);
    w.line(' * @param fields 结构化字段 / structured fields');
  }
  if (event.error) {
    w.line(' * @param error 可选错误 / optional error');
  }
  w.line(' */');
}

function docText(text) {
  return text.replace(/\*\//g, '* /').replace(/\r?\n/g, ' ');
}

function str(text) {
  return JSON.stringify(text);
}

function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

class Writer {
  constructor() {
    this.lines = [];
    this.depth = 0;
  }

  line(text = '') {
    if (text === '') {
      this.lines.push('');
      return;
    }
    this.lines.push(`${'  '.repeat(this.depth)}${text}`);
  }

  block(header, body) {
    this.line(`${header} {`);
    this.depth++;
    body();
    this.depth--;
    this.line('}');
  }

  toString() {
    return `${this.lines.join('\n')}\n`;
  }
}
