// Execute the repository Kotlin reference (only clock/RNG/logging replaced) and
// emit the same cases as Hypium tests for execution on the HarmonyOS runtime.
//
// 前提：Kotlin 参考源码不在本仓库内，需要自备并用 KOTLIN_DOUYIN_SOURCE 指向它，
// 否则本脚本直接退出 2。产物有两个：entry/src/test/ABogus.test.ets（生成的 Hypium
// 用例）和 docs/abogus/reference-results.json（源文件 SHA-256、固定输入与用例数）。
// 跑 scripts/test-abogus-device.sh 之前必须先跑本脚本——设备脚本要读那个 JSON 对数量。
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..');
const source = process.env.KOTLIN_DOUYIN_SOURCE;
if (!source) { console.error('Set KOTLIN_DOUYIN_SOURCE to the Android Kotlin SDK directory'); process.exit(2); }
const javaHome = process.env.JAVA_HOME || '/Applications/DevEco-Studio.app/Contents/jbr/Contents/Home';
const kotlinHome = process.env.KOTLIN_HOME || '/Applications/Android Studio.app/Contents/plugins/Kotlin/kotlinc';
const bc = process.env.BCPROV_JAR || execFileSync('find', [path.join(os.homedir(), '.gradle/caches/modules-2/files-2.1/org.bouncycastle/bcprov-jdk18on'), '-name', '*.jar'], {encoding:'utf8'}).trim().split('\n')[0];
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'abogus-test-'));
const vectors = [];
const times = [0, 4294967293, 1099511627773, 1789430400000, 281474976710653];
const inputs = [[], [['aid','6383'],['aweme_id','1234567890123456789'],['msToken','']], [['空 格','中文 😀 +/?!\'()~*'],['zero','\0'],['broken','\ud800X\udc00']], [['z','last'],['a','first']], [['long','abcd'.repeat(300)]]];
for (let t = 0; t < times.length; t++) for (let p = 0; p < inputs.length; p++) for (let delta = 0; delta < 5; delta++) {
  vectors.push({time:times[t], params:inputs[p], rng:[0, 0.1234567, 0.99999999, (delta + 0.1) / 5]});
}
function ktString(x) { return '"' + [...x.split('')].map(c => '\\u' + c.charCodeAt(0).toString(16).padStart(4,'0')).join('') + '"'; }
try {
  const hashes = {};
  for (const relative of ['ABogus.kt', 'utils/SM3HashUtils.kt']) {
    const raw = fs.readFileSync(path.join(source, relative), 'utf8');
    hashes[relative] = createHash('sha256').update(raw).digest('hex');
    const patched = raw.replace('import kotlin.random.Random', 'import fixture.Fixed as Random')
      .replace('import android.util.Log', 'import fixture.Log')
      .replace('Instant.now().toEpochMilli()', 'fixture.Fixed.time');
    fs.writeFileSync(path.join(tmp, path.basename(relative)), patched);
  }
  fs.writeFileSync(path.join(tmp,'Fixed.kt'), `package fixture
object Fixed { var time = 0L; var index = 0; var values = doubleArrayOf(0.0)
fun nextDouble(): Double = values[index++]
fun nextInt(from: Int, until: Int): Int = from + (nextDouble() * (until-from)).toInt()
}
object Log { fun d(tag: String, message: String): Int = 0 }
`);
  fs.writeFileSync(path.join(tmp,'Main.kt'), `import com.lightningstudio.dashiell.sdk.douyin.ABogus
import com.lightningstudio.dashiell.sdk.douyin.URLParametersToURLQueryString
import fixture.Fixed
fun main() {\n` + vectors.map(v => `Fixed.time=${v.time}L; Fixed.index=0; Fixed.values=doubleArrayOf(${v.rng.map(x => Number.isInteger(x) ? x.toFixed(1) : String(x)).join(',')})
run { val p=linkedMapOf<String,String>(${v.params.map(([k,v])=>`${ktString(k)} to ${ktString(v)}`).join(',')}); println(URLParametersToURLQueryString().urlEncode(p)+"\\t"+ABogus().getValue(p)) }`).join('\n') + '\n}');
  execFileSync(path.join(kotlinHome,'bin/kotlinc'), ['ABogus.kt','SM3HashUtils.kt','Fixed.kt','Main.kt','-cp',bc,'-include-runtime','-d','reference.jar'], {cwd:tmp, env:{...process.env,JAVA_HOME:javaHome},stdio:['ignore','pipe','pipe']});
  const lines = execFileSync(path.join(javaHome,'bin/java'), ['-cp',`${tmp}/reference.jar:${bc}`,'MainKt'],{encoding:'utf8'}).trimEnd().split('\n');
  assert.equal(lines.length,vectors.length);
  const require = createRequire(import.meta.url);
  const ts = require(process.env.TYPESCRIPT_PATH || '/Applications/DevEco-Studio.app/Contents/tools/hvigor/hvigor/node_modules/typescript');
  for (const name of ['SM3','ABogus']) {
    fs.writeFileSync(path.join(tmp,name+'.js'),ts.transpileModule(fs.readFileSync(path.join(root,`entry/src/main/ets/common/douyin/${name}.ets`),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText);
  }
  const {ABogus} = require(path.join(tmp,'ABogus.js'));
  const {SM3} = require(path.join(tmp,'SM3.js'));
  for (const len of [0,3,55,56,63,64,65,1000,10000]) {
    const bytes=Array.from({length:len},(_,i)=>i&255);
    assert.equal(Buffer.from(SM3.digest(bytes)).toString('hex'),createHash('sm3').update(Buffer.from(bytes)).digest('hex'));
  }
  let tests = `// Generated by scripts/test-abogus.mjs from executed Kotlin reference.\nimport { describe, it, expect } from '@ohos/hypium';\nimport { ABogus } from '../main/ets/common/douyin/ABogus';\nimport { SM3 } from '../main/ets/common/douyin/SM3';\nexport default function abogusTest() {\n  describe('ABogusKotlinParity', () => {\n`;
  vectors.forEach((v,i)=> {
    const [query,expected]=lines[i].split('\t');
    let n=0; const signer=new ABogus(()=>v.time,()=>v.rng[n++]); const params=new Map(v.params);
    assert.equal(ABogus.serialize(params),query,`encoding ${i}`);
    assert.equal(signer.getValue(params),expected,`signature ${i}`);
    tests += `    it('kotlinVector${i}', 0, () => {\n      const p = new Map<string, string>();\n` + v.params.map(([k,val])=>`      p.set(${JSON.stringify(k)}, ${JSON.stringify(val)});\n`).join('') + `      const rng: number[] = ${JSON.stringify(v.rng)};\n      let index = 0;\n      const signer = new ABogus(() => ${v.time}, () => rng[index++]);\n      expect(ABogus.serialize(p)).assertEqual(${JSON.stringify(query)});\n      expect(signer.getValue(p)).assertEqual(${JSON.stringify(expected)});\n    });\n`;
  });
  tests += `    it('sm3ABC', 0, () => {\n      const hex = SM3.digest([97, 98, 99]).map((v: number): string => v.toString(16).padStart(2, '0')).join('');\n      expect(hex).assertEqual('66c7f0f462eeedd9d1f2d46bdc10e4e24167c4875cf2f7a2297da02b8f4ba8e0');\n    });\n  });\n}\n`;
  fs.writeFileSync(path.join(root,'entry/src/test/ABogus.test.ets'), tests);
  fs.mkdirSync(path.join(root,'docs/abogus'),{recursive:true});
  fs.writeFileSync(path.join(root,'docs/abogus/reference-results.json'),JSON.stringify({source,hashes,count:vectors.length,hostParity:'PASS',sm3OpenSSLChecks:9,vectors:vectors.map((v,i)=>({...v,query:lines[i].split('\t')[0],expected:lines[i].split('\t')[1]}))},null,2)+'\n');
  console.log(`PASS: executed Kotlin vs transpiled source: ${vectors.length} vectors; 9 SM3/OpenSSL checks. Generated Hypium suite for real ArkTS execution.`);
} finally { fs.rmSync(tmp,{recursive:true,force:true}); }
